#!/usr/bin/env node
// Builds the Samsung Tizen app folder (build/tizen/app) from web/ and tizen/.
//
// 2019 Samsung TVs (Tizen 5.0) run Chromium 63, which lacks syntax the web UI
// uses (?. ?? ||= catch without a binding) and flex "gap". So, unlike the
// Android APK which packages web/ as-is, this build:
//   - bundles tizen/js/main.js (polyfills + shell + web/js/main.js) into one
//     classic script lowered to Chromium 63 with esbuild, swapping
//     web/js/platform/{device,player}.js for the Tizen versions;
//   - rewrites CSS `inset` into top/right/bottom/left and adds margin-based
//     fallbacks for flex `gap` under html.no-flex-gap;
//   - copies fonts, images, config.xml, icon.png and index.html.
//
//   node scripts/build-tizen.mjs            release build (minified)
//   node scripts/build-tizen.mjs --dev      readable output, DEV logging on
//   node scripts/build-tizen.mjs --out DIR  build somewhere else
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const DEV = args.includes('--dev');
const outIdx = args.indexOf('--out');
const OUT = path.resolve(outIdx >= 0 ? args[outIdx + 1] : path.join(ROOT, 'build/tizen/app'));
export const TARGET = 'chrome63';   // Samsung 2019 (Tizen 5.0) web engine

const WEB = path.join(ROOT, 'web');
const TIZEN = path.join(ROOT, 'tizen');

// ---- CSS -------------------------------------------------------------------------

function expandInset(value) {
  const v = value.trim().split(/\s+/);
  const [t, r = t, b = t, l = r] = v;
  return 'top:' + t + ';right:' + r + ';bottom:' + b + ';left:' + l;
}

// Split a stylesheet into top-level rules: [{ selector, body }]. Our CSS has
// no nested blocks other than @font-face, which are passed through.
function rules(css) {
  const out = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(css))) out.push({ selector: m[1].replace(/\/\*[\s\S]*?\*\//g, '').trim(), body: m[2] });
  return out;
}

export function legacyCss(css) {
  // inset (Chromium 87) -> four longhands.
  let result = css.replace(/(^|[;{\s])inset\s*:\s*([^;}!]+?)(\s*!important)?\s*(?=[;}])/g,
    (all, pre, value, imp) => pre + expandInset(value).split(';').map(d => d + (imp || '')).join(';'));
  // flex gap (Chromium 84) -> margins on every child after the first.
  const fallbacks = [];
  for (const { selector, body } of rules(result)) {
    if (selector.startsWith('@')) continue;
    const g = /(?:^|[;\s])gap\s*:\s*([^;]+)/.exec(body);
    if (!g) continue;
    const [rowGap, colGap = rowGap] = g[1].replace('!important', '').trim().split(/\s+/);
    const column = /flex-direction\s*:\s*column/.test(body);
    const decl = column ? 'margin-top:' + rowGap : 'margin-left:' + colGap;
    const sel = selector.split(',').map(s => 'html.no-flex-gap ' + s.trim() + ' > * + *').join(',\n');
    fallbacks.push(sel + ' { ' + decl + '; }');
  }
  if (fallbacks.length) result += '\n\n/* Flex gap fallbacks for Chromium < 84 (generated by build-tizen.mjs) */\n' + fallbacks.join('\n') + '\n';
  return result;
}

// ---- JS ----------------------------------------------------------------------------

// web/js/platform/X.js -> tizen/js/platform/X.js
const tizenPlatform = {
  name: 'tizen-platform',
  setup(b) {
    b.onLoad({ filter: /[\\/]web[\\/]js[\\/]platform[\\/](device|player)\.js$/ }, async ({ path: p }) => {
      const swap = path.join(TIZEN, 'js/platform', path.basename(p));
      return { contents: await fs.promises.readFile(swap, 'utf8'), loader: 'js', resolveDir: path.dirname(swap) };
    });
    if (DEV) {
      b.onLoad({ filter: /[\\/]web[\\/]js[\\/]config\.js$/ }, async ({ path: p }) => ({
        contents: (await fs.promises.readFile(p, 'utf8')).replace('export const DEV = false;', 'export const DEV = true;'),
        loader: 'js',
      }));
    }
  },
};

function copyDir(from, to, filter = () => true) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dst, filter);
    else if (filter(src)) fs.copyFileSync(src, dst);
  }
}

export async function buildTizen() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, 'js'), { recursive: true });
  fs.mkdirSync(path.join(OUT, 'css'), { recursive: true });

  const version = /<widget[^>]*\sversion="([^"]+)"/.exec(fs.readFileSync(path.join(TIZEN, 'config.xml'), 'utf8'))[1];
  await build({
    entryPoints: [path.join(TIZEN, 'js/main.js')],
    bundle: true,
    format: 'iife',
    target: TARGET,
    outfile: path.join(OUT, 'js/easyplex.js'),
    minify: !DEV,
    legalComments: 'none',
    logLevel: 'warning',
    plugins: [tizenPlatform],
    banner: { js: '/* EasyPlex for Samsung Tizen ' + version + ' — GPL-3.0, see https://github.com/danfulton72/EasyPlex */' },
  });

  for (const f of fs.readdirSync(path.join(WEB, 'css'))) {
    fs.writeFileSync(path.join(OUT, 'css', f), legacyCss(fs.readFileSync(path.join(WEB, 'css', f), 'utf8')));
  }
  fs.writeFileSync(path.join(OUT, 'css/tizen.css'), legacyCss(fs.readFileSync(path.join(TIZEN, 'css/tizen.css'), 'utf8')));
  copyDir(path.join(WEB, 'fonts'), path.join(OUT, 'fonts'));
  copyDir(path.join(WEB, 'img'), path.join(OUT, 'img'));
  for (const f of ['config.xml', 'icon.png', 'index.html']) fs.copyFileSync(path.join(TIZEN, f), path.join(OUT, f));
  fs.copyFileSync(path.join(ROOT, 'LICENSE'), path.join(OUT, 'LICENSE'));
  return { out: OUT, version };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildTizen().then(({ out, version }) => {
    console.log('built ' + (DEV ? 'dev' : 'release') + ' ' + version + ' -> ' + path.relative(process.cwd(), out));
  }).catch(e => { console.error(e.message || e); process.exit(1); });
}
